export type StudioLocale = "ja" | "en" | "ko" | "zh-Hans" | "fr" | "pt-BR" | "it" | "de" | "ru";

export const LOCALE_OPTIONS = [
  { value: "ja", label: "日本語" },
  { value: "en", label: "English" },
  { value: "ko", label: "한국어" },
  { value: "zh-Hans", label: "简体中文" },
  { value: "fr", label: "Français" },
  { value: "pt-BR", label: "Português (Brasil)" },
  { value: "it", label: "Italiano" },
  { value: "de", label: "Deutsch" },
  { value: "ru", label: "Русский" },
] as const;

export function isStudioLocale(value: string | null): value is StudioLocale {
  return LOCALE_OPTIONS.some((option) => option.value === value);
}

export function getTemplateLanguage(locale: StudioLocale): SpeechLanguage {
  if (locale === "ja") return "ja-JP";
  if (locale === "en") return "en-US";
  return locale;
}

